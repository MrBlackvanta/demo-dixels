const day = (offset: number): string => shiftDay(todayKey(), offset);

const at = (clock: string, offset = 0): string => {
  const [hours, minutes] = clock.split(':').map(Number);
  const date = new Date(`${day(offset)}T00:00:00`);
  date.setHours(hours, minutes, 0, 0);
  return date.toISOString();
};

const minutesFromNow = (offset: number): string => {
  const date = new Date();
  date.setMinutes(date.getMinutes() + offset, 0, 0);
  return date.toISOString();
};

const hoursAgo = (offset: number): string => minutesFromNow(-offset * 60);

